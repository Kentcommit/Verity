package com.example.scamguardv1.utils

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.os.Environment
import android.widget.Toast
import com.example.scamguardv1.domain.model.DetectionResult
import com.example.scamguardv1.utils.Logger
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.io.IOException
import java.text.SimpleDateFormat
import java.util.*

object PdfGenerator {

    suspend fun generateAnalysisReport(context: Context, fileName: String, result: DetectionResult) = withContext(Dispatchers.IO) {
        val pdfDocument = PdfDocument()
        val paint = Paint()
        val titlePaint = Paint()

        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        // Header
        titlePaint.textAlign = Paint.Align.CENTER
        titlePaint.textSize = 24f
        titlePaint.isFakeBoldText = true
        canvas.drawText("Verity Analysis Report", 297f, 50f, titlePaint)

        // Metadata
        paint.textSize = 12f
        val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault())
        val date = dateFormat.format(Date())
        
        var yPos = 100f
        canvas.drawText("Date: $date", 50f, yPos, paint)
        yPos += 20f
        canvas.drawText("File Name: $fileName", 50f, yPos, paint)
        yPos += 40f

        // Score
        paint.textSize = 16f
        paint.isFakeBoldText = true
        canvas.drawText("Overall Suspicion Score: ${result.score.toInt()}%", 50f, yPos, paint)
        yPos += 30f

        // Reasons
        paint.textSize = 14f
        canvas.drawText("Detection Reasons:", 50f, yPos, paint)
        yPos += 20f
        paint.isFakeBoldText = false
        paint.textSize = 12f
        result.reasons.forEach { reason ->
            canvas.drawText("• $reason", 70f, yPos, paint)
            yPos += 20f
        }
        yPos += 20f

        // Features
        result.features?.let { features ->
            paint.isFakeBoldText = true
            paint.textSize = 14f
            canvas.drawText("Voice Pattern Details:", 50f, yPos, paint)
            yPos += 20f
            paint.isFakeBoldText = false
            paint.textSize = 12f
            canvas.drawText("Spectral Centroid: ${features.spectralCentroid}", 70f, yPos, paint)
            yPos += 20f
            canvas.drawText("Zero Crossing Rate: ${features.zeroCrossingRate}", 70f, yPos, paint)
            yPos += 20f
            canvas.drawText("Energy Stability: ${features.energyStability}", 70f, yPos, paint)
            yPos += 20f
            canvas.drawText("Harmonics Ratio: ${features.harmonicsRatio}", 70f, yPos, paint)
            yPos += 20f
        }

        // Footer
        paint.color = Color.GRAY
        paint.textSize = 10f
        canvas.drawText("Generated by ScamGuard Verity App", 50f, 800f, paint)

        pdfDocument.finishPage(page)

        val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
        val file = File(downloadsDir, "Verity_Report_${System.currentTimeMillis()}.pdf")

        try {
            pdfDocument.writeTo(FileOutputStream(file))
            withContext(Dispatchers.Main) {
                Toast.makeText(context, "PDF saved to Downloads", Toast.LENGTH_LONG).show()
            }
        } catch (e: IOException) {
            Logger.e("Failed to write PDF report", e)
            withContext(Dispatchers.Main) {
                Toast.makeText(context, "Error saving PDF: ${e.message}", Toast.LENGTH_SHORT).show()
            }
        } finally {
            pdfDocument.close()
        }
    }
}
